def _write_if_missing(path, content):
    if os.path.exists(path):
        return False
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, 'w', encoding='utf-8') as f:
        f.write(content)
    return True


def make_cover(folder, fname, c1, c2, accent, glyph, w=800, h=600):
    """کاور SVG انتزاعی (بدون متن) برای محصول/دوره/مقاله"""
    path = os.path.join(_BASE, folder, fname)
    svg = _COVER_TMPL.format(
        w=w, h=h, c1=c1, c2=c2, accent=accent,
        glyph=_GLYPHS.get(glyph, _GLYPHS['layers']),
        cx=w // 2, cy=int(h * 0.46), r1=int(h * 0.30), r1b=int(h * 0.38),
        r2=int(h * 0.55), r3=int(h * 0.42))
    _write_if_missing(path, svg)
    return '/uploads/%s/%s' % (folder, fname)


def make_avatar(fname, c1, c2):
    path = os.path.join(_BASE, 'avatars', fname)
    svg = _AVATAR_TMPL.format(c1=c1, c2=c2, x1=44, r1=30)
    _write_if_missing(path, svg)
    return '/uploads/avatars/%s' % fname


