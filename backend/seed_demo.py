def _shop_seed(users):
    # داده‌های پایه فروشگاه (نسخه اول — idempotent)
    from seed_shop import run_shop_seed
    run_shop_seed()

    # دسته‌های جدید
    for slug, name in _NEW_CATS:
        if not ShopCategory.query.filter_by(slug=slug).first():
            db.session.add(ShopCategory(name=name, slug=slug))
    db.session.commit()

    def _cat_id(slug):
        c = ShopCategory.query.filter_by(slug=slug).first()
        return c.id if c else None

    # محصولات جدید
    for pidx, (name, cslug, price, disc, feat, flash, glyph, colors, sales, sd, desc) in enumerate(_NEW_PRODUCTS):
        if ShopProduct.query.filter_by(name=name).first():
            continue
        c1, c2, acc = colors
        img = make_cover('products', 'seed-prod-%d.svg' % (pidx + 1), c1, c2, acc, glyph)
        db.session.add(ShopProduct(
            name=name, slug=name.replace(' ', '-').replace('(', '').replace(')', ''),
            short_desc=sd, description=desc, price=price, discount_percent=disc,
            category_id=_cat_id(cslug), image_url=img, featured=feat,
            is_active=True, sales_count=sales))
    db.session.commit()

    # فلش‌سِیل همیشه زنده بماند (تمدید خودکار برای محصولات نمونه)
    for pname in ('اپلیکیشن مدیریت پروژه رساتسک', 'ربات تلگرام فروشگاهی ماه‌پیام', 'چت‌بات پشتیبانی هوشمند'):
        p = ShopProduct.query.filter_by(name=pname).first()
        if p and (not p.flash_until or p.flash_until < datetime.utcnow()):
            p.flash_until = datetime.utcnow() + timedelta(days=7)
    db.session.commit()

    # نظرات محصولات جدید
    for pname, revs in _NEW_REVIEWS.items():
        p = ShopProduct.query.filter_by(name=pname).first()
        if not p:
            continue
        uids = list(users.values())
        for i, (stars, cmt, uname) in enumerate(revs):
            uid = uids[i % len(uids)]
            if ShopReview.query.filter_by(product_id=p.id, username=uname).first():
                continue
            db.session.add(ShopReview(product_id=p.id, user_id=uid, username=uname,
                                      rating=stars, comment=cmt,
                                      created_at=datetime.utcnow() - timedelta(days=4 * i + 1)))
    db.session.commit()

    # باندل سوم
    title, names, disc, desc = _BUNDLE3
    if not ShopBundle.query.filter_by(title=title).first():
        ids = [ShopProduct.query.filter_by(name=n).first().id
               for n in names if ShopProduct.query.filter_by(name=n).first()]
        db.session.add(ShopBundle(title=title, slug=title.replace(' ', '-'),
                                  description=desc, discount_percent=disc,
                                  product_ids=json.dumps(ids), is_active=True))
    db.session.commit()

    # مقالات جدید با کاور
    art_colors = [('#0b1020', '#0e2233', '#00f2ff', 'cart'),
                  ('#0b1020', '#141033', '#a78bfa', 'bot'),
                  ('#0b1020', '#0c2418', '#34d399', 'layers'),
                  ('#0b1020', '#251508', '#f59e0b', 'palette')]
    for idx, (t, ex, body) in enumerate(_NEW_ARTICLES):
        if ShopArticle.query.filter_by(title=t).first():
            continue
        c1, c2, acc, gl = art_colors[idx % len(art_colors)]
        cover = make_cover('articles', 'seed-art-%d.svg' % (idx + 1), c1, c2, acc, gl, w=800, h=420)
        db.session.add(ShopArticle(title=t, slug=t.replace(' ', '-').replace('٪', ''),
                                   excerpt=ex, body=body, cover_url=cover,
                                   is_published=True,
                                   created_at=datetime.utcnow() - timedelta(days=3 * idx + 2)))
    db.session.commit()

