def _courses_seed(users, admin):
    a_uid = admin.id
    uids = list(users.values())
    created_courses = []
    for (title, cat, lvl, dur, tags, glyph, acc, views, desc, html) in _NEW_COURSES:
        c = Course.query.filter_by(title=title).first()
        if not c:
            idx = len(created_courses)
            c1 = '#0b1020'
            c2 = {'#00f2ff': '#0a1c2c', '#a78bfa': '#161233', '#34d399': '#0a2418',
                  '#ec4899': '#221020', '#f59e0b': '#221a06', '#f472b6': '#221018',
                  '#22d3ee': '#08202a', '#7dd3fc': '#0a2030', '#10b981': '#082418'}.get(acc, '#101a2e')
            thumb = make_cover('courses', 'seed-course-%d.svg' % (idx + 1), c1, c2, acc, glyph)
            c = Course(title=title, description=desc, content=html, category=cat,
                       level=lvl, duration=dur, tags=tags, thumbnail_url=thumb,
                       instructor_id=a_uid, is_published=True, view_count=views,
                       created_at=datetime.utcnow() - timedelta(days=6 * idx + 4))
            db.session.add(c)
            db.session.flush()
        created_courses.append(c)
    db.session.commit()

    # امتیازها (یکتا: user_id + course_id)
    for idx, (title, revs) in enumerate(_COURSE_REVIEWS.items()):
        c = Course.query.filter_by(title=title).first()
        if not c:
            continue
        for i, (score, _) in enumerate(revs):
            uid = uids[(i + idx) % len(uids)]
            if not Rating.query.filter_by(user_id=uid, course_id=c.id).first():
                db.session.add(Rating(score=score, user_id=uid, course_id=c.id,
                                      created_at=datetime.utcnow() - timedelta(days=2 * i + 3)))
    db.session.commit()

    # نظرات + پاسخ‌ها (نویسنده باید کاربر واقعی باشد چون author.full_name سریال می‌شود)
    for title, comments in _COURSE_COMMENTS.items():
        c = Course.query.filter_by(title=title).first()
        if not c:
            continue
        created_ids = []
        base = datetime.utcnow() - timedelta(days=5)
        for i, (text, author, reply_idx) in enumerate(comments):
            if Comment.query.filter_by(course_id=c.id, content=text).first():
                continue
            parent = created_ids[reply_idx] if reply_idx is not None and reply_idx < len(created_ids) else None
            cm = Comment(content=text, user_id=users[author] if author in users else a_uid,
                         course_id=c.id, parent_id=parent, is_approved=True,
                         created_at=base + timedelta(hours=9 * i))
            db.session.add(cm)
            db.session.flush()
            created_ids.append(cm.id)
    db.session.commit()

    # آزمون‌ها و سوالات
    for (qtitle, course_idx, questions) in _QUIZZES:
        course = created_courses[course_idx] if course_idx < len(created_courses) else None
        if not course or Quiz.query.filter_by(title=qtitle).first():
            continue
        q = Quiz(title=qtitle, description='آزمون نمونه برای سنجش یادگیری — پس از مطالعه درس مربوطه شرکت کنید.',
                 course_id=course.id, passing_score=70, time_limit=15, max_attempts=3, is_active=True)
        db.session.add(q)
        db.session.flush()
        for i, (text, opts, correct, expl) in enumerate(questions):
            db.session.add(Question(quiz_id=q.id, question_text=text,
                                    question_type='multiple_choice',
                                    options=json.dumps(opts, ensure_ascii=False),
                                    correct_answer=opts[correct], points=10,
                                    explanation=expl, order=i))
    db.session.commit()


def _forum_seed(users, admin):
    for name, slug, color in _FORUM_TAGS:
        if not ForumTag.query.filter_by(slug=slug).first():
            db.session.add(ForumTag(name=name, slug=slug, color=color))
    db.session.commit()

    a_uid = admin.id
    for idx, (catslug, title, author, content, tags, pinned, solved, views, up, posts) in enumerate(_FORUM_TOPICS):
        t = ForumTopic.query.filter_by(title=title).first()
        if t:
            continue
        cat = ForumCategory.query.filter_by(slug=catslug).first()
        if not cat:
            continue
        base = datetime.utcnow() - timedelta(days=14 - idx)
        t = ForumTopic(category_id=cat.id,
                       user_id=users.get(author, a_uid),
                       title=title, slug=title.replace(' ', '-').replace('؟', '')[:200],
                       content=content, tags=','.join(tags), is_pinned=pinned,
                       is_solved=solved, views=views, upvotes=up,
                       created_at=base, last_post_at=base)
        db.session.add(t)
        db.session.flush()
        t.posts_count = 0
        for i, (pauthor, ptext, is_ans) in enumerate(posts):
            p = ForumPost(topic_id=t.id, user_id=users.get(pauthor, a_uid), content=ptext,
                          is_answer=is_ans, upvotes=5 if is_ans else 2,
                          created_at=base + timedelta(hours=8 * (i + 1)))
            db.session.add(p)
            t.posts_count += 1
            t.last_post_at = p.created_at
            t.last_post_user_id = p.user_id
        # تگ‌های topic
        for tg in tags:
            ft = ForumTag.query.filter_by(name=tg).first()
            if ft and not TopicTag.query.filter_by(topic_id=t.id, tag_id=ft.id).first():
                db.session.add(TopicTag(topic_id=t.id, tag_id=ft.id))
        db.session.commit()

    # شمارنده دسته‌ها
    for cat in ForumCategory.query.all():
        cat.topics_count = ForumTopic.query.filter_by(category_id=cat.id).count()
        cat.posts_count = db.session.query(db.func.count(ForumPost.id)).join(
            ForumTopic, ForumPost.topic_id == ForumTopic.id).filter(
            ForumTopic.category_id == cat.id).scalar() or 0
        last = ForumTopic.query.filter_by(category_id=cat.id).order_by(
            ForumTopic.last_post_at.desc()).first()
        if last:
            cat.last_post_at = last.last_post_at
    db.session.commit()


def _misc_seed(users, admin):
    # کیف پول نمونه
    for uname, (amount, note) in _WALLETS:
        u = User.query.filter_by(username=uname).first()
        if not u:
            continue
        exists = BizWalletTx.query.filter_by(user_id=u.id, note=note).first()
        if not exists:
            db.session.add(BizWalletTx(user_id=u.id, amount=amount, kind='deposit',
                                       status='done', note=note,
                                       ref_code='SEED-%s' % uname.upper()))
    # کوپن عمومی
    if not BizCoupon.query.filter_by(code='WELCOME20').first():
        db.session.add(BizCoupon(code='WELCOME20', percent=20, max_uses=500, active=True))
    # پیشنهادهای نمونه
    for (subject, content, author, cat, status, resp) in _SUGGESTIONS:
        if Suggestion.query.filter_by(subject=subject).first():
            continue
        db.session.add(Suggestion(subject=subject, content=content,
                                  user_id=users.get(author, admin.id), category=cat,
                                  status=status, admin_response=resp))
    db.session.commit()


